module.exports = async function handler(req, res) {
    res.setHeader('Access-Control-Allow-Credentials', true);
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'POST,OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

    if (req.method === 'OPTIONS') return res.status(200).end();
    if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

    const { messages } = req.body || {};
    if (!Array.isArray(messages) || messages.length === 0) {
        return res.status(400).json({ error: 'Invalid request: messages array required' });
    }

    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey) return res.status(500).json({ error: 'Server misconfigured' });

    try {
        const groqRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
            method: 'POST',
            headers: {
                'Authorization': `Bearer ${apiKey}`,
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({
                model: 'llama-3.3-70b-versatile',
                messages: [{ role: 'system', content: SYSTEM_PROMPT }, ...messages],
                max_tokens: 350,
                temperature: 0.75
            })
        });

        if (groqRes.status === 429) {
            return res.status(429).json({
                error: 'rate_limit',
                message: 'Das tägliche Anfragelimit wurde erreicht. Bitte morgen wieder versuchen.'
            });
        }

        if (!groqRes.ok) {
            const body = await groqRes.text();
            console.error('Groq upstream error:', groqRes.status, body);
            return res.status(502).json({ error: 'upstream_error', message: 'KI-Dienst momentan nicht verfügbar.' });
        }

        const data = await groqRes.json();
        const content = data.choices?.[0]?.message?.content ?? '';
        return res.status(200).json({ content });

    } catch (err) {
        console.error('Handler error:', err);
        return res.status(500).json({ error: 'server_error', message: 'Ein unerwarteter Fehler ist aufgetreten.' });
    }
};
